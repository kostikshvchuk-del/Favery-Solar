function getLang() {
  return localStorage.getItem('faveryLang') || 'en';
}

function setLang(lang) {
  localStorage.setItem('faveryLang', lang);
}

function t(key) {
  return translations[getLang()][key] || translations.en[key] || key;
}

function applyTranslations() {
  const lang = getLang();
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = t(key);
    } else {
      el.textContent = t(key);
    }
  });
  document.documentElement.lang = lang;
  const langBtn = document.getElementById('langBtn');
  if (langBtn) {
    langBtn.textContent = lang === 'en' ? 'UA' : 'EN';
    langBtn.title = lang === 'en' ? 'Перейти на українську' : 'Switch to English';
  }
}
